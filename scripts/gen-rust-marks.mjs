// Regenerate the Rust column-width Mark table from the same JS engine semantics.
import fs from 'node:fs';
const ranges=[];let start=-1;
for(let cp=0;cp<=0x10ffff;cp++) {
 const mark=/\p{Mark}/u.test(String.fromCodePoint(cp));
 if(mark && start<0)start=cp;
 if(!mark && start>=0){ranges.push([start,cp-1]);start=-1;}
}
if(start>=0)ranges.push([start,0x10ffff]);
const output=`// Generated by scripts/gen-rust-marks.mjs; Unicode ${process.versions.unicode} (Node ${process.version}).\n// Same \\p{Mark} classification as the TS activity core; no terminal state.\npub const UNICODE_VERSION: &str = "${process.versions.unicode}";\npub const MARK_RANGES: &[(u32,u32)] = &[\n${ranges.map(([a,b])=>`    (0x${a.toString(16)},0x${b.toString(16)}),`).join('\n')}\n];\n`;
fs.writeFileSync(new URL('../rust/pitools-core/src/marks.rs',import.meta.url),output);
console.log(`Generated ${ranges.length} ranges, Unicode ${process.versions.unicode}`);
