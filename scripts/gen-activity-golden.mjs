// Regenerates tests/fixtures/activity-golden.json from the TS activity core.
// Run only when an intentional, documented activity behavior change is made.
process.env.TZ = 'UTC';
const fs = await import('node:fs');
const { scenario } = await import('../tests/activity-scenarios.mjs');
const scenarios = [];
for (let seed = 1; seed <= 24; seed++) scenarios.push(scenario(seed, 36, seed % 5 === 0 ? 'en-US' : 'zh-CN'));
const out = new URL('../tests/fixtures/activity-golden.json', import.meta.url);
fs.writeFileSync(out, JSON.stringify({ note: 'Generated by scripts/gen-activity-golden.mjs from the TS core (TZ=UTC). Frames are host protocol frames; expect maps view id to [line, phase, failure, live, nextWakeAt].', scenarios }) + '\n');
console.log(`wrote ${scenarios.length} scenarios, ${scenarios.reduce((n, s) => n + Object.keys(s.expect).length, 0)} views, ${fs.statSync(out).size} bytes`);
